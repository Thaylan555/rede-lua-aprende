-- 3) Native search + recommendation engine ---------------------------------
create or replace function public.rede_lua_search_activities(p_query text, p_limit integer default 12)
returns table (
  id uuid,
  title text,
  subject text,
  description text,
  difficulty text,
  tags text[],
  status text,
  question_count bigint,
  created_at timestamptz,
  updated_at timestamptz,
  score double precision
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  with input as (
    select trim(coalesce(p_query,'')) as raw,
           websearch_to_tsquery('portuguese'::regconfig, trim(coalesce(p_query,''))) as tsq
  )
  select a.id, a.title, a.subject, a.description, a.difficulty, a.tags, a.status,
         (select count(*) from public.rede_lua_questions q where q.activity_id = a.id) as question_count,
         a.created_at, a.updated_at,
         (
           ts_rank_cd(a.search_vector, input.tsq)::double precision * 4.0
           + extensions.similarity(lower(a.title), lower(input.raw)) * 2.4
           + extensions.similarity(lower(a.subject), lower(input.raw)) * 1.6
           + case when lower(a.title) like '%' || lower(input.raw) || '%' then 1.2 else 0 end
           + case when lower(a.subject) like '%' || lower(input.raw) || '%' then 0.8 else 0 end
           + case when exists (select 1 from unnest(a.tags) t where lower(t) like '%' || lower(input.raw) || '%') then 0.9 else 0 end
         ) as score
  from public.rede_lua_activities a
  cross join input
  where a.status = 'published'
    and char_length(input.raw) between 2 and 90
    and (
      a.search_vector @@ input.tsq
      or extensions.similarity(lower(a.title), lower(input.raw)) > 0.12
      or extensions.similarity(lower(a.subject), lower(input.raw)) > 0.18
      or lower(a.title) like '%' || lower(input.raw) || '%'
      or lower(a.subject) like '%' || lower(input.raw) || '%'
      or lower(a.description) like '%' || lower(input.raw) || '%'
      or exists (select 1 from unnest(a.tags) t where lower(t) like '%' || lower(input.raw) || '%')
    )
  order by score desc, a.updated_at desc
  limit greatest(1, least(coalesce(p_limit,12), 30));
$$;

grant execute on function public.rede_lua_search_activities(text,integer) to anon, authenticated;


create or replace function public.rede_lua_after_answer_learning()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid;
  v_subject text;
  v_xp integer;
begin
  select p.user_id, a.subject
    into v_user, v_subject
  from public.rede_lua_participants p
  join public.rede_lua_games g on g.id = new.game_id
  join public.rede_lua_activities a on a.id = g.activity_id
  where p.id = new.participant_id;

  if v_user is null or v_subject is null then return new; end if;

  insert into public.rede_lua_mastery(user_id,subject,attempts,correct_count,mastery_score,confidence,last_result,updated_at)
  values(
    v_user,
    v_subject,
    1,
    case when new.correct then 1 else 0 end,
    case when new.correct then 0.5800 else 0.4200 end,
    0.2500,
    new.correct,
    now()
  )
  on conflict(user_id,subject) do update set
    attempts = public.rede_lua_mastery.attempts + 1,
    correct_count = public.rede_lua_mastery.correct_count + case when new.correct then 1 else 0 end,
    mastery_score = round(greatest(0.0500, least(0.9800,
      public.rede_lua_mastery.mastery_score * 0.84 + (case when new.correct then 1.0 else 0.0 end) * 0.16
    ))::numeric,4),
    confidence = round(least(0.9900, 1.0 - (1.0 / (1.0 + ((public.rede_lua_mastery.attempts + 1)::numeric / 3.0))))::numeric,4),
    last_result = new.correct,
    updated_at = now();

  insert into public.rede_lua_subject_affinity(user_id,subject,score)
  values(v_user,v_subject,case when new.correct then 4 else 1 end)
  on conflict(user_id,subject) do update set score=public.rede_lua_subject_affinity.score+excluded.score,updated_at=now();

  v_xp := case when new.correct then greatest(18, least(85, 18 + (new.awarded_points / 5))) else 5 end;
  update public.rede_lua_profiles
  set
    xp = xp + v_xp,
    level = greatest(level, 1 + floor((xp + v_xp)::numeric / 500)::integer),
    streak_days = case
      when last_learning_date = current_date then streak_days
      when last_learning_date = current_date - 1 then streak_days + 1
      else 1
    end,
    last_learning_date = current_date,
    updated_at = now()
  where user_id = v_user;

  return new;
end;
$$;

revoke all on function public.rede_lua_after_answer_learning() from public, anon, authenticated;

drop trigger if exists rede_lua_after_answer_learning_trg on public.rede_lua_answers;
create trigger rede_lua_after_answer_learning_trg
after insert on public.rede_lua_answers
for each row execute function public.rede_lua_after_answer_learning();

create or replace function public.rede_lua_recommend_activities(p_limit integer default 8)
returns table (
  id uuid,
  title text,
  subject text,
  description text,
  difficulty text,
  tags text[],
  status text,
  question_count bigint,
  created_at timestamptz,
  updated_at timestamptz,
  score double precision
)
language sql
stable
security invoker
set search_path = public
as $$
  select a.id, a.title, a.subject, a.description, a.difficulty, a.tags, a.status,
         (select count(*) from public.rede_lua_questions q where q.activity_id = a.id) as question_count,
         a.created_at, a.updated_at,
         (
           coalesce(least(3.0, ln(1 + af.score::double precision)), 0.0)
           + coalesce((1.0 - m.mastery_score::double precision) * 2.2, 0.45)
           + case
               when m.mastery_score >= 0.78 and a.difficulty = 'hard' then 1.0
               when m.mastery_score between 0.42 and 0.78 and a.difficulty = 'medium' then 0.8
               when (m.mastery_score is null or m.mastery_score < 0.42) and a.difficulty = 'easy' then 0.7
               else 0.15
             end
           + greatest(0.0, 1.0 - extract(epoch from (now() - a.updated_at)) / 2592000.0) * 0.35
         ) as score
  from public.rede_lua_activities a
  left join public.rede_lua_subject_affinity af
    on af.user_id = (select auth.uid()) and lower(af.subject) = lower(a.subject)
  left join public.rede_lua_mastery m
    on m.user_id = (select auth.uid()) and lower(m.subject) = lower(a.subject)
  where a.status = 'published'
  order by score desc, a.updated_at desc
  limit greatest(1, least(coalesce(p_limit,8), 20));
$$;

grant execute on function public.rede_lua_recommend_activities(integer) to anon, authenticated;

-- 6) Teacher System #2: Radar de Aprendizagem -------------------------------
create or replace function public.rede_lua_teacher_radar(p_days integer default 30)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
with
  cfg as (select greatest(1,least(coalesce(p_days,30),180)) as days),
  teacher_games as (
    select g.id, g.activity_id, g.code, g.status, g.created_at, g.ended_at, a.title, a.subject
    from public.rede_lua_games g
    join public.rede_lua_activities a on a.id=g.activity_id
    cross join cfg
    where g.host_id=(select auth.uid()) and g.created_at >= now() - make_interval(days => cfg.days)
  ),
  ans as (
    select an.*, p.user_id, p.display_name, tg.title as activity_title, tg.subject
    from public.rede_lua_answers an
    join public.rede_lua_participants p on p.id=an.participant_id
    join teacher_games tg on tg.id=an.game_id
  ),
  hotspots as (
    select q.id as question_id, left(q.prompt,220) as prompt, tg.title as activity_title, tg.subject,
           count(an.id)::int as total_answers,
           count(an.id) filter (where an.correct=false)::int as wrong_answers,
           case when count(an.id)=0 then 0 else round((count(an.id) filter (where an.correct=false)::numeric / count(an.id)::numeric)*100,1) end as error_rate
    from teacher_games tg
    join public.rede_lua_questions q on q.activity_id=tg.activity_id
    left join public.rede_lua_answers an on an.game_id=tg.id and an.question_id=q.id
    group by q.id,q.prompt,tg.title,tg.subject
    having count(an.id) > 0
    order by error_rate desc, total_answers desc
    limit 8
  ),
  learner_subjects as (
    select distinct a.user_id, a.display_name, a.subject
    from ans a where a.user_id is not null
  ),
  learners as (
    select ls.user_id, max(ls.display_name) as display_name, ls.subject,
           m.mastery_score, m.confidence, m.attempts,
           case when m.mastery_score < 0.42 then 'intervir' when m.mastery_score < 0.68 then 'acompanhar' else 'fluente' end as signal
    from learner_subjects ls
    join public.rede_lua_mastery m on m.user_id=ls.user_id and lower(m.subject)=lower(ls.subject)
    group by ls.user_id,ls.subject,m.mastery_score,m.confidence,m.attempts
    order by m.mastery_score asc, m.confidence desc
    limit 24
  )
select jsonb_build_object(
  'summary', jsonb_build_object(
    'games', (select count(*) from teacher_games),
    'participants', (select count(distinct participant_id) from ans),
    'answers', (select count(*) from ans),
    'accuracy', (select coalesce(round((count(*) filter (where correct)::numeric / nullif(count(*),0))*100,1),0) from ans)
  ),
  'hotspots', coalesce((select jsonb_agg(to_jsonb(h)) from hotspots h),'[]'::jsonb),
  'learners', coalesce((select jsonb_agg(to_jsonb(l)) from learners l),'[]'::jsonb),
  'recentGames', coalesce((select jsonb_agg(to_jsonb(x)) from (
    select id,code,status,title,subject,created_at,ended_at from teacher_games order by created_at desc limit 8
  ) x),'[]'::jsonb)
)
where public.rede_lua_is_teacher();
$$;

grant execute on function public.rede_lua_teacher_radar(integer) to authenticated;

-- 7) Student System: Constelação --------------------------------------------
create or replace function public.rede_lua_student_constellation()
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
with
  me as (
    select p.user_id,p.display_name,p.xp,p.level,p.streak_days
    from public.rede_lua_profiles p
    where p.user_id=(select auth.uid())
  ),
  mastery as (
    select m.subject,m.mastery_score,m.confidence,m.attempts,m.correct_count,m.last_result,m.updated_at
    from public.rede_lua_mastery m
    where m.user_id=(select auth.uid())
    order by m.mastery_score asc, m.updated_at desc
  ),
  today as (
    select a.id,a.correct,g.activity_id,act.subject,act.difficulty
    from public.rede_lua_answers a
    join public.rede_lua_participants p on p.id=a.participant_id
    join public.rede_lua_games g on g.id=a.game_id
    join public.rede_lua_activities act on act.id=g.activity_id
    where p.user_id=(select auth.uid()) and a.answered_at >= current_date
  ),
  weak_subject as (
    select subject from mastery order by mastery_score asc, confidence desc limit 1
  ),
  strong_subject as (
    select subject from mastery order by mastery_score desc, confidence desc limit 1
  ),
  recover_activity as (
    select a.id,a.title,a.subject,a.description,a.difficulty
    from public.rede_lua_activities a
    where a.status='published'
      and lower(a.subject)=lower(coalesce((select subject from weak_subject),a.subject))
    order by case a.difficulty when 'easy' then 0 when 'medium' then 1 else 2 end, a.updated_at desc
    limit 1
  ),
  explore_activity as (
    select a.id,a.title,a.subject,a.description,a.difficulty
    from public.rede_lua_activities a
    where a.status='published'
      and not exists (select 1 from mastery m where lower(m.subject)=lower(a.subject))
    order by md5(coalesce((select auth.uid())::text,'anon') || current_date::text || a.id::text)
    limit 1
  ),
  challenge_activity as (
    select a.id,a.title,a.subject,a.description,a.difficulty
    from public.rede_lua_activities a
    where a.status='published'
      and (not exists(select 1 from strong_subject) or lower(a.subject)=lower((select subject from strong_subject)))
    order by case a.difficulty when 'hard' then 0 when 'medium' then 1 else 2 end, a.updated_at desc
    limit 1
  ),
  missions as (
    select 'recuperar'::text as type, 'Fortaleça um ponto fraco'::text as label,
           r.id as activity_id,r.title,r.subject,r.description,r.difficulty,
           3::int as target,
           least(3,(select count(*)::int from today t where lower(t.subject)=lower(r.subject))) as progress,
           90::int as reward_xp
    from recover_activity r
    union all
    select 'explorar','Descubra uma nova matéria',e.id,e.title,e.subject,e.description,e.difficulty,
           2, least(2,(select count(*)::int from today t where lower(t.subject)=lower(e.subject))),70
    from explore_activity e
    union all
    select 'desafio','Teste o que você domina',c.id,c.title,c.subject,c.description,c.difficulty,
           4, least(4,(select count(*)::int from today t where lower(t.subject)=lower(c.subject))),120
    from challenge_activity c
  )
select jsonb_build_object(
  'profile', coalesce((select to_jsonb(me) from me),'{}'::jsonb),
  'mastery', coalesce((select jsonb_agg(to_jsonb(m)) from mastery m),'[]'::jsonb),
  'missions', coalesce((select jsonb_agg(to_jsonb(ms)) from missions ms),'[]'::jsonb),
  'today', jsonb_build_object(
    'answers',(select count(*) from today),
    'correct',(select count(*) from today where correct),
    'accuracy',(select coalesce(round((count(*) filter (where correct)::numeric / nullif(count(*),0))*100,1),0) from today)
  )
)
where (select auth.uid()) is not null;
$$;


create or replace function public.rede_lua_save_forge_question(
  p_subject text,
  p_skill_key text,
  p_prompt text,
  p_choices jsonb,
  p_correct_index integer,
  p_explanation text default '',
  p_difficulty text default 'medium',
  p_tags text[] default '{}'
) returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare v_id uuid;
begin
  if not public.rede_lua_is_teacher() then raise exception 'TEACHER_REQUIRED'; end if;
  if jsonb_typeof(p_choices) <> 'array' or jsonb_array_length(p_choices) not between 2 and 5 then raise exception 'INVALID_CHOICES'; end if;
  if p_correct_index < 0 or p_correct_index >= jsonb_array_length(p_choices) then raise exception 'INVALID_CORRECT_INDEX'; end if;
  insert into public.rede_lua_question_bank(owner_id,subject,skill_key,prompt,choices,correct_index,explanation,difficulty,tags)
  values((select auth.uid()), trim(p_subject), coalesce(nullif(trim(p_skill_key),''),'geral'), trim(p_prompt), p_choices,
         p_correct_index, left(coalesce(p_explanation,''),900), p_difficulty, coalesce(p_tags,'{}'))
  returning id into v_id;
  return v_id;
end;
$$;


-- 1) Native search index -----------------------------------------------------
alter table public.rede_lua_activities
  add column if not exists search_vector tsvector;

create or replace function public.rede_lua_refresh_activity_search_vector()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.search_vector := to_tsvector(
    'portuguese'::regconfig,
    coalesce(new.title,'') || ' ' || coalesce(new.subject,'') || ' ' ||
    coalesce(new.description,'') || ' ' || coalesce(array_to_string(new.tags,' '),'')
  );
  return new;
end;
$$;

update public.rede_lua_activities
set search_vector = to_tsvector(
  'portuguese'::regconfig,
  coalesce(title,'') || ' ' || coalesce(subject,'') || ' ' ||
  coalesce(description,'') || ' ' || coalesce(array_to_string(tags,' '),'')
)
where search_vector is null;

drop trigger if exists rede_lua_activity_search_vector_trg on public.rede_lua_activities;
create trigger rede_lua_activity_search_vector_trg
before insert or update of title,subject,description,tags on public.rede_lua_activities
for each row execute function public.rede_lua_refresh_activity_search_vector();

create index if not exists rede_lua_activities_search_vector_idx
  on public.rede_lua_activities using gin (search_vector);
create index if not exists rede_lua_activities_title_trgm_idx
  on public.rede_lua_activities using gin (lower(title) extensions.gin_trgm_ops);
create index if not exists rede_lua_activities_subject_trgm_idx
  on public.rede_lua_activities using gin (lower(subject) extensions.gin_trgm_ops);

